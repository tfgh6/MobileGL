import subprocess, re, os
nm = "C:/Program Files/Android/android-ndk-r29/toolchains/llvm/prebuilt/windows-x86_64/bin/llvm-nm.exe"
libs = [
    "C:/Gradle/sfpew-apk/lib/arm64-v8a/libSimpleFPEWrapper.so",
    "D:/Projects/MobileGL/build_android2/libMobileGL.so",
]
outdir = "D:/Projects/MobileGL/android-plugin/app/src/main/cpp/renderer_proxy"
os.makedirs(outdir, exist_ok=True)
syms = set()
for lib in libs:
    txt = subprocess.run([nm, "-D", "--defined-only", lib], capture_output=True, text=True).stdout
    for line in txt.splitlines():
        parts = line.split()
        if len(parts) < 3:
            continue
        typ, name = parts[1], parts[2]
        if typ not in ("T", "t", "W", "w"):
            continue
        if re.match(r"^(gl[A-Z]|egl[A-Z])", name):
            syms.add(name)
syms = sorted(syms)
print("symbols", len(syms))
with open(os.path.join(outdir, "stubs.S"), "w", newline="\n") as f:
    f.write("// generated by gen_proxy.py: AArch64 trampolines for the renderer proxy\n")
    f.write(".text\n")
    for s in syms:
        f.write(".p2align 2\n.global %s\n.type %s,%%function\n%s:\n    adrp x16, p_%s\n    ldr x16, [x16, :lo12:p_%s]\n    br x16\n.size %s, .-%s\n" % (s, s, s, s, s, s, s))
    f.write('.section .data,"aw"\n')
    for s in syms:
        f.write(".p2align 2\n.global p_%s\n.hidden p_%s\np_%s: .quad 0\n" % (s, s, s))
with open(os.path.join(outdir, "proxy_symbols.h"), "w", newline="\n") as f:
    f.write("#pragma once\n")
    for s in syms:
        f.write("extern void *p_%s;\n" % s)
    f.write("typedef struct { const char *name; void **slot; } ProxySymbol;\n")
    f.write("static const ProxySymbol g_proxy_symbols[] = {\n")
    for s in syms:
        f.write('  {"%s", &p_%s},\n' % (s, s))
    f.write("};\nstatic const unsigned g_proxy_symbol_count = sizeof(g_proxy_symbols) / sizeof(g_proxy_symbols[0]);\n")
print("written", outdir)