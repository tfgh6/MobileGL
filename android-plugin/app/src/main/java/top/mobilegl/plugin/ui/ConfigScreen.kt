private const val DEFAULT_CONFIG = """# Generated by MobileGL Plugin.
# 键名与 MobileGL / SimpleFPEWrapper 的环境变量一致。
MOBILEGL_BACKEND_TYPE=DirectVulkan
LIBGL_ES=3
POJAV_RENDERER=opengles3
SFPEW_EGL=libMobileGL.so
"""

@Composable
fun ConfigScreen(
    writer: RuntimeConfigWriter,
    status: RuntimeConfigWriter.Status,
    onStatusChanged: (RuntimeConfigWriter.Status) -> Unit,
) {
    val context = LocalContext.current
    var text by remember { mutableStateOf(writer.readShared() ?: DEFAULT_CONFIG) }
    var message by remember { mutableStateOf<String?>(null) }

    fun save() {
        val s = writer.writeRaw(text)
        onStatusChanged(s)
        message = if (s.sharedWritten) "已写入 " + s.sharedPath else "共享路径不可写：" + (s.reason ?: "")
    }

    Column(
        modifier = Modifier
            .fillMaxSize()
            .verticalScroll(rememberScrollState())
            .padding(16.dp),
        verticalArrangement = Arrangement.spacedBy(12.dp),
    ) {
        SectionCard("启动配置文件") {
            Text(
                status.sharedPath,
                style = MaterialTheme.typography.labelSmall,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
            )
            Text(
                if (status.sharedWritten) "已写入共享路径（启动器进程可读）" else "尚未写入共享路径：" + (status.reason ?: ""),
                style = MaterialTheme.typography.bodySmall,
            )
            Spacer(Modifier.height(6.dp))
            Text(
                "说明：官方 CI 构建的 libMobileGL.so 只读环境变量，不读这个文件；" +
                    "本项目补丁库、以及后续 PanVK 驱动会读它。Zalith/FCL 的“渲染器设置”里也能直接改同名选项。",
                style = MaterialTheme.typography.labelSmall,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
            )
            Spacer(Modifier.height(8.dp))
            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                Button(onClick = { save() }) { Text("保存配置") }
                OutlinedButton(onClick = { text = writer.readShared() ?: DEFAULT_CONFIG }) { Text("重新读取") }
                OutlinedButton(onClick = {
                    text = DEFAULT_CONFIG
                }) { Text("恢复模板") }
            }
            if (!hasAllFilesAccess()) {
                OutlinedButton(onClick = { openAllFilesSettings(context) }) { Text("授予“所有文件访问权限”") }
            }
            message?.let {
                Spacer(Modifier.height(6.dp))
                Text(it, style = MaterialTheme.typography.bodySmall)
            }
        }

        SectionCard("常用选项") {
            Text(
                "点击即改上面的配置文件；保存后写入 /sdcard/MobileGL/runtime.conf。",
                style = MaterialTheme.typography.labelSmall,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
            )
            Spacer(Modifier.height(8.dp))
            OptionSelect(
                label = "渲染后端",
                options = listOf("DirectVulkan", "DirectGLES"),
                value = readKey(text, "MOBILEGL_BACKEND_TYPE", "DirectVulkan"),
                onSelect = { text = setKey(text, "MOBILEGL_BACKEND_TYPE", it) },
            )
            OptionSelect(
                label = "SFPEW 后端",
                options = listOf("libMobileGL.so", "libEGL.so"),
                value = readKey(text, "SFPEW_EGL", "libMobileGL.so"),
                onSelect = { text = setKey(text, "SFPEW_EGL", it) },
            )
            OptionToggle("禁用 GPU 计时器查询", "MOBILEGL_DISABLE_TIMERQUERY", text) { text = setKey(text, "MOBILEGL_DISABLE_TIMERQUERY", if (it) "1" else "0") }
            OptionToggle("禁用 Vulkan subgroup", "MOBILEGL_DISABLE_SUBGROUP", text) { text = setKey(text, "MOBILEGL_DISABLE_SUBGROUP", if (it) "1" else "0") }
            OptionToggle("R11G11B10F 回退格式", "MOBILEGL_VULKAN_R11G11B10F_FALLBACK", text) { text = setKey(text, "MOBILEGL_VULKAN_R11G11B10F_FALLBACK", if (it) "1" else "0") }
            OptionToggle("Espryt 使用 ANGLE", "MOBILEGL_ESPRYT_USE_ANGLE", text) { text = setKey(text, "MOBILEGL_ESPRYT_USE_ANGLE", if (it) "1" else "0") }
            OptionToggle("SFPEW 宽松上下文", "SFPEW_RELAXED_CONTEXT", text) { text = setKey(text, "SFPEW_RELAXED_CONTEXT", if (it) "1" else "0") }
            OptionToggle("SFPEW 关闭 MultiDrawArrays", "SFPEW_NO_MULTIDRAWARRAYS", text) { text = setKey(text, "SFPEW_NO_MULTIDRAWARRAYS", if (it) "1" else "0") }
            OptionToggle("SFPEW 关闭列表批处理", "SFPEW_NO_LIST_BATCH", text) { text = setKey(text, "SFPEW_NO_LIST_BATCH", if (it) "1" else "0") }
        }

        SectionCard("原始配置") {
            OutlinedTextField(
                value = text,
                onValueChange = { text = it },
                modifier = Modifier.fillMaxWidth(),
                minLines = 10,
                textStyle = MaterialTheme.typography.bodySmall,
                label = { Text("runtime.conf") },
            )
            Spacer(Modifier.height(8.dp))
            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                OutlinedButton(onClick = {
                    val clipboard = context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
                    clipboard.setPrimaryClip(ClipData.newPlainText("runtime.conf", text))
                }) { Text("复制") }
                OutlinedButton(onClick = {
                    val intent = Intent(Intent.ACTION_SEND).apply {
                        type = "text/plain"
                        putExtra(Intent.EXTRA_TEXT, text)
                    }
                    context.startActivity(Intent.createChooser(intent, "分享配置文件"))
                }) { Text("分享") }
            }
        }
    }
}

@Composable
private fun OptionSelect(label: String, options: List<String>, value: String, onSelect: (String) -> Unit) {
    Column(Modifier.fillMaxWidth().padding(vertical = 4.dp)) {
        Text(label, style = MaterialTheme.typography.bodySmall, fontWeight = FontWeight.Medium)
        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            options.forEach { option ->
                FilterChip(selected = option == value, onClick = { onSelect(option) }, label = { Text(option) })
            }
        }
    }
}

@Composable
private fun OptionToggle(label: String, key: String, text: String, onToggle: (Boolean) -> Unit) {
    val enabled = readKey(text, key, "0") == "1"
    Row(
        modifier = Modifier.fillMaxWidth().padding(vertical = 4.dp),
        verticalAlignment = Alignment.CenterVertically,
    ) {
        Column(Modifier.weight(1f)) {
            Text(label, style = MaterialTheme.typography.bodySmall)
            Text(key, style = MaterialTheme.typography.labelSmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
        }
        Switch(checked = enabled, onCheckedChange = onToggle)
    }
}

private fun readKey(text: String, key: String, fallback: String): String =
    text.lineSequence()
        .map { it.trim() }
        .filter { it.isNotEmpty() && !it.startsWith("#") && it.contains('=') }
        .map { it.substringBefore('=').trim() to it.substringAfter('=').trim() }
        .firstOrNull { it.first == key }?.second ?: fallback

private fun setKey(text: String, key: String, value: String): String {
    val lines = text.lines().toMutableList()
    var replaced = false
    for (i in lines.indices) {
        val trimmed = lines[i].trim()
        if (trimmed.isEmpty() || trimmed.startsWith("#") || !trimmed.contains('=')) continue
        if (trimmed.substringBefore('=').trim() == key) {
            lines[i] = key + "=" + value
            replaced = true
            break
        }
    }
    if (!replaced) {
        lines.add(key + "=" + value)
    }
    return lines.joinToString("\n")
}

private fun hasAllFilesAccess(): Boolean =
    if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) Environment.isExternalStorageManager() else true

private fun openAllFilesSettings(context: Context) {
    val packageUri = Uri.parse("package:" + context.packageName)
    runCatching {
        context.startActivity(Intent(Settings.ACTION_MANAGE_APP_ALL_FILES_ACCESS_PERMISSION, packageUri))
    }.onFailure {
        context.startActivity(Intent(Settings.ACTION_MANAGE_ALL_FILES_ACCESS_PERMISSION))
    }
}
